begin;
select plan(3);
select pgflow_tests.reset_db();
select pgflow.track_worker_function('my-function');
set local app.settings.jwt_secret = 'super-secret-jwt-token-with-at-least-32-characters-long';
create temporary table invocation as select function_name, invoked, request_id from pgflow.ensure_workers();
select is((select count(*) from invocation where request_id is not null), 1::bigint, 'returns the request_id column');
select ok((select request_id is not null from invocation where function_name = 'my-function'), 'request_id is not NULL');
select ok((select request_id > 0 from invocation), 'request_id is a positive bigint from pg_net');
select finish();
rollback;
