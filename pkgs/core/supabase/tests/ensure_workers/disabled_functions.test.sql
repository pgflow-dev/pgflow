begin;
select plan(2);
select pgflow_tests.reset_db();
select pgflow.track_worker_function('enabled-function');
select pgflow.track_worker_function('disabled-function');
update pgflow.worker_functions set enabled = false where function_name = 'disabled-function';
set local app.settings.jwt_secret = 'super-secret-jwt-token-with-at-least-32-characters-long';
create temporary table invocation as select * from pgflow.ensure_workers();
select is((select count(*) from invocation), 1::bigint, 'only enabled functions are returned');
select is((select function_name from invocation), 'enabled-function', 'returns the enabled function');
select finish();
rollback;
